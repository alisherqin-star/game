import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const code=readFileSync(new URL('../art/renderer-example.js',import.meta.url),'utf8');
const {createEnvironmentRenderer,tileVariant}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const manifest=JSON.parse(readFileSync(new URL('../art/manifest.json',import.meta.url),'utf8'));
const images=Object.fromEntries(manifest.assets.map(a=>[a.id,{id:a.id}]));
const calls=[];const ctx={drawImage:(...args)=>calls.push(args)};
const renderer=createEnvironmentRenderer(ctx,manifest,images);
renderer.draw('deco/env_village_cottage',100,200,10,20);
assert.deepEqual(calls.pop().slice(1),[42,100]);
renderer.animated('torch',.125,20,40);
assert.equal(calls.pop()[0].id,'deco/env_torch_1');
renderer.animated('torch',.5,20,40);
assert.equal(calls.pop()[0].id,'deco/env_torch_0');
renderer.background('backgrounds/env_forest_layer_0',-113,384,224);
assert.ok(calls[0][1]<=0);assert.ok(calls.at(-1)[1]+384>=384);
for(let i=1;i<calls.length;i++)assert.equal(calls[i][1]-calls[i-1][1],384);
for(let x=-20;x<20;x++)for(let y=-20;y<20;y++)assert.ok(tileVariant(x,y)>=0&&tileVariant(x,y)<4);
assert.throws(()=>tileVariant(0,0,0),RangeError);
assert.equal(renderer.draw('missing',0,0),false);
assert.equal(ctx.imageSmoothingEnabled,false);
console.log('Art renderer: anchor, animation loop, negative-camera repeat and stable variants passed.');
